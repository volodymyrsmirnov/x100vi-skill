"""Help for running camera commands outside an agent's command sandbox.

Codex and Claude Code can run shell commands in a sandbox that hides USB devices, so every
command that talks to the camera has to be allowed to run outside it. Nothing here changes
an agent's configuration unless the user explicitly asks for the Codex rules file to be written.
"""
from __future__ import annotations

import os
import shutil
from pathlib import Path

READ_COMMANDS = ["doctor", "get", "backup", "preview", "verify", "validate", "recipes", "schema", "--version"]
WRITE_COMMANDS = ["set", "restore", "--self-update"]
SKILL_HOMES = (".agents/skills", ".codex/skills", ".claude/skills")
WHY_READ = "x100vi talks to the camera over USB, which is not reachable inside the sandbox"
WHY_WRITE = "x100vi changes camera settings or installs itself; it needs USB or the network, so approve each run"


def codex_home() -> Path:
    """Codex's configuration folder: $CODEX_HOME when set, else ~/.codex (as `install-skill --codex` uses)."""
    return Path(os.environ.get("CODEX_HOME") or Path.home() / ".codex")


def launcher_paths(home: Path | None = None) -> list[str]:
    """Every installed copy of the skill's launcher, as an agent would spell its path."""
    home = home or Path.home()
    roots = [home / rel for rel in SKILL_HOMES]
    roots.append(codex_home() / "skills")       # may differ from ~/.codex/skills when CODEX_HOME is set
    found: list[str] = []
    for root in roots:
        path = root / "x100vi" / "scripts" / "x100vi.sh"
        if path.is_file():
            for spelling in (str(path), str(path.resolve())):
                if spelling not in found:
                    found.append(spelling)
    return found


def tool_paths() -> list[str]:
    names = ["x100vi"]
    installed = shutil.which("x100vi")
    if installed and installed not in names:
        names.append(installed)
    return names


def _starlark_list(items: list[str]) -> str:
    return "[" + ", ".join('"' + i.replace("\\", "\\\\").replace('"', '\\"') + '"' for i in items) + "]"


def codex_rules(tools: list[str] | None = None, launchers: list[str] | None = None) -> str:
    """A Codex .rules file: read-only commands run unsandboxed, writes run unsandboxed after a prompt."""
    tools = tools if tools is not None else tool_paths()
    launchers = launchers if launchers is not None else launcher_paths()
    prefixes = [_starlark_list(tools)]
    if launchers:
        prefixes.append(_starlark_list(["sh", "bash"]) + ", " + _starlark_list(launchers))
    blocks = [
        "# x100vi: let Codex reach the camera. Generated by `x100vi sandbox-help`.\n"
        "# USB devices are invisible inside the sandbox, so these commands must run outside it.\n"
        "# Reading and previewing run without a prompt; anything that writes still asks first.\n"
    ]
    for prefix in prefixes:
        for commands, decision, why in ((READ_COMMANDS, "allow", WHY_READ), (WRITE_COMMANDS, "prompt", WHY_WRITE)):
            blocks.append(
                "prefix_rule(\n"
                f"    pattern = [{prefix}, {_starlark_list(commands)}],\n"
                f'    decision = "{decision}",\n'
                f'    justification = "{why}",\n'
                ")\n")
    return "\n".join(blocks)


def codex_rules_path() -> Path:
    return codex_home() / "rules" / "x100vi.rules"


def claude_settings(tools: list[str] | None = None, launchers: list[str] | None = None) -> dict:
    """The settings.json fragment that keeps these commands out of Claude Code's sandbox."""
    tools = tools if tools is not None else tool_paths()
    launchers = launchers if launchers is not None else launcher_paths()
    patterns = [f"{t} *" for t in tools] + [f"sh {path} *" for path in launchers]
    return {"sandbox": {"excludedCommands": patterns}}
