func TestGeneratedRulesAreAcceptedByCodex(t *testing.T) {
	codex, err := exec.LookPath("codex")
	if err != nil {
		t.Skip("needs the Codex CLI to check the rules with its own parser")
	}
	launcher := "/home/me/.agents/skills/x100vi/scripts/x100vi.sh"
	rules := filepath.Join(t.TempDir(), "x100vi.rules")
	if err := os.WriteFile(rules, []byte(CodexRules([]string{"x100vi"}, []string{launcher})), 0o644); err != nil {
		t.Fatal(err)
	}
	decision := func(argv ...string) any {
		out, err := exec.Command(codex, append([]string{"execpolicy", "check", "--rules", rules, "--"}, argv...)...).Output()
		if err != nil {
			t.Fatalf("codex execpolicy: %v", err)
		}
		var res map[string]any
		if err := json.Unmarshal(out, &res); err != nil {
			t.Fatalf("%s: %v", out, err)
		}
		return res["decision"]
	}
	cases := []struct {
		argv []string
		want any
	}{
		{[]string{"x100vi", "doctor", "--json"}, "allow"},
		{[]string{"sh", launcher, "preview", "a.RAF", "-r", "b.json"}, "allow"},
		{[]string{"sh", launcher, "set", "C1", "a.json"}, "prompt"},
		{[]string{"x100vi", "restore", "a.json", "--yes"}, "prompt"},
		{[]string{"sh", "/tmp/other.sh", "doctor"}, nil},
		{[]string{"x100vi", "install-skill", "--claude"}, nil},
	}
	for _, c := range cases {
		if got := decision(c.argv...); got != c.want {
			t.Errorf("%v: got %v, want %v", c.argv, got, c.want)
		}
	}
}
