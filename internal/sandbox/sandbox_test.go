func realTemp(t *testing.T) string {
	t.Helper()
	dir, err := filepath.EvalSymlinks(t.TempDir()) // macOS: /var -> /private/var
	if err != nil {
		t.Fatal(err)
	}
	return dir
}

func writeLauncher(t *testing.T, path string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte("#!/bin/sh\n"), 0o755); err != nil {
		t.Fatal(err)
	}
}

func TestLauncherPathsFindsInstalledCopies(t *testing.T) {
	tmp := realTemp(t)
	t.Setenv("CODEX_HOME", filepath.Join(tmp, "no-codex"))
	script := filepath.Join(tmp, ".agents", "skills", "x100vi", "scripts", "x100vi.sh")
	writeLauncher(t, script)
	if got := LauncherPaths(tmp); len(got) == 0 || got[0] != script {
		t.Errorf("%v", got)
	}
	if got := LauncherPaths(filepath.Join(tmp, "nobody")); len(got) != 0 {
		t.Errorf("%v", got)
	}
}

func TestLauncherPathsResolveSymlinks(t *testing.T) {
	tmp := realTemp(t)
	t.Setenv("CODEX_HOME", filepath.Join(tmp, "no-codex"))
	real := filepath.Join(tmp, "checkout", "skills", "x100vi")
	writeLauncher(t, filepath.Join(real, "scripts", "x100vi.sh"))
	link := filepath.Join(tmp, "home", ".claude", "skills", "x100vi")
	os.MkdirAll(filepath.Dir(link), 0o755)
	if err := os.Symlink(real, link); err != nil {
		t.Skip("no symlinks here:", err)
	}
	got := LauncherPaths(filepath.Join(tmp, "home"))
	want := []string{filepath.Join(link, "scripts", "x100vi.sh"), filepath.Join(real, "scripts", "x100vi.sh")}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got %v, want %v", got, want)
	}
}

func TestLauncherPathsFollowACustomCodexHome(t *testing.T) {
	tmp := realTemp(t)
	custom := filepath.Join(tmp, "elsewhere", "codex")
	script := filepath.Join(custom, "skills", "x100vi", "scripts", "x100vi.sh")
	writeLauncher(t, script)
	t.Setenv("CODEX_HOME", custom)
	if got := LauncherPaths(filepath.Join(tmp, "home")); !reflect.DeepEqual(got, []string{script}) {
		t.Errorf("%v", got)
	}
	if CodexRulesPath() != filepath.Join(custom, "rules", "x100vi.rules") {
		t.Errorf("rules path %s", CodexRulesPath())
	}
	t.Setenv("CODEX_HOME", "")
	if got := LauncherPaths(filepath.Join(tmp, "home")); len(got) != 0 {
		t.Errorf("%v", got)
	}
	home, _ := os.UserHomeDir()
	if CodexHome() != filepath.Join(home, ".codex") {
		t.Errorf("default codex home %s", CodexHome())
	}
}

