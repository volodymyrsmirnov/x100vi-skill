func TestDetect(t *testing.T) {
	cases := []struct {
		env  map[string]string
		want string
	}{
		{map[string]string{"CODEX_SANDBOX": "seatbelt"}, "Codex"},
		{map[string]string{"CODEX_SANDBOX_NETWORK_DISABLED": "1"}, "Codex"},
		{map[string]string{"X100VI_SANDBOX": "Example"}, "Example"},
		{map[string]string{}, ""},
		{map[string]string{"CODEX_SANDBOX_NETWORK_DISABLED": "0"}, ""},
	}
	for _, c := range cases {
		if got := Detect(c.env); got != c.want {
			t.Errorf("%v: got %q, want %q", c.env, got, c.want)
		}
	}
}

func clearSandboxEnv(t *testing.T) {
	for _, v := range []string{"CODEX_SANDBOX", "CODEX_SANDBOX_NETWORK_DISABLED", "X100VI_SANDBOX"} {
		t.Setenv(v, "")
	}
}

func TestErrorNamesTheSandbox(t *testing.T) {
	clearSandboxEnv(t)
	if Error() != nil {
		t.Fatalf("not sandboxed")
	}
	t.Setenv("CODEX_SANDBOX", "seatbelt")
	e, ok := errs.As(Error())
	if !ok || !strings.Contains(e.Message, "Codex sandbox") || !strings.Contains(e.Hint, "not a camera or cable problem") ||
		e.Kind.Exit != 14 || e.Kind.Name != "sandboxed" {
		t.Errorf("%+v", e)
	}
}

func TestCodexRulesAllowReadsAndPromptForWrites(t *testing.T) {
	rules := CodexRules([]string{"x100vi"}, []string{"/home/me/.agents/skills/x100vi/scripts/x100vi.sh"})
	if n := strings.Count(rules, "prefix_rule("); n != 4 {
		t.Fatalf("%d rules", n)
	}
	for _, want := range []string{
		`pattern = [["x100vi"], ["doctor", "get", "backup", "preview"`,
		`[["sh", "bash"], ["/home/me/.agents/skills/x100vi/scripts/x100vi.sh"], ["set", "restore"`,
	} {
		if !strings.Contains(rules, want) {
			t.Errorf("missing %s", want)
		}
	}
	if len(strings.Split(rules, `decision = "allow"`)) != 3 || len(strings.Split(rules, `decision = "prompt"`)) != 3 {
		t.Errorf("two allow and two prompt rules expected")
	}
	for _, block := range strings.Split(rules, "prefix_rule(")[1:] {
		writes := strings.Contains(block, `"set"`)
		if strings.Contains(block, `decision = "prompt"`) != writes || strings.Contains(block, `decision = "allow"`) == writes {
			t.Errorf("wrong decision:\n%s", block)
		}
	}
	if strings.Contains(rules, `"install-skill"`) || strings.Contains(rules, `"sandbox-help"`) {
		t.Errorf("never pre-approved")
	}
}

