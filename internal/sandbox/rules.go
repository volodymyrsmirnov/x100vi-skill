package sandbox

// Help for running camera commands outside an agent's command sandbox.
//
// Codex and Claude Code can run shell commands in a sandbox that hides USB devices, so every command
// that talks to the camera has to be allowed to run outside it. Nothing here changes an agent's
// configuration unless the user explicitly asks for the Codex rules file to be written.

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// ReadCommands only read from the camera (or print); they may run outside the sandbox without a prompt.
var ReadCommands = []string{"doctor", "get", "backup", "preview", "verify", "validate", "recipes", "schema", "--version"}

// WriteCommands change camera settings or replace the tool; the user approves each run.
var WriteCommands = []string{"set", "restore", "--self-update"}

// SkillHomes are the skills folders, relative to the home folder, the skill may be installed in.
var SkillHomes = []string{".agents/skills", ".codex/skills", ".claude/skills"}

const (
	whyRead  = "x100vi talks to the camera over USB, which is not reachable inside the sandbox"
	whyWrite = "x100vi changes camera settings or installs itself; it needs USB or the network, so approve each run"
)

// CodexHome is Codex's configuration folder: $CODEX_HOME when set, else ~/.codex.
func CodexHome() string {
	if v := os.Getenv("CODEX_HOME"); v != "" {
		return v
	}
	return filepath.Join(homeDir(), ".codex")
}

// CodexRulesPath is where the Codex rules file goes.
func CodexRulesPath() string { return filepath.Join(CodexHome(), "rules", "x100vi.rules") }

func homeDir() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return "."
	}
	return home
}

func resolved(p string) string {
	abs, err := filepath.Abs(p)
	if err != nil {
		return p
	}
	if real, err := filepath.EvalSymlinks(abs); err == nil {
		return real
	}
	return abs
}

func appendNew(list []string, items ...string) []string {
	for _, it := range items {
		dup := false
		for _, x := range list {
			if x == it {
				dup = true
				break
			}
		}
		if !dup {
			list = append(list, it)
		}
	}
	return list
}

// LauncherPaths lists every installed copy of the skill's POSIX launcher (scripts/x100vi.sh), as an
// agent would spell its path and with symlinks resolved. home is "" for the user's home folder.
func LauncherPaths(home string) []string {
	if home == "" {
		home = homeDir()
	}
	var roots []string
	for _, rel := range SkillHomes {
		roots = append(roots, filepath.Join(home, filepath.FromSlash(rel)))
	}
	roots = append(roots, filepath.Join(CodexHome(), "skills")) // differs from ~/.codex/skills when CODEX_HOME is set
	found := []string{}
	for _, root := range roots {
		p := filepath.Join(root, "x100vi", "scripts", "x100vi.sh")
		if info, err := os.Stat(p); err == nil && info.Mode().IsRegular() {
			found = appendNew(found, p, resolved(p))
		}
	}
	return found
}

// ToolPaths are the spellings of the tool an agent may run directly: the bare name, the copy on PATH
// (if any) and this binary itself (the launchers keep it in a cache folder), symlinks resolved.
func ToolPaths() []string {
	names := []string{"x100vi"}
	if p, err := exec.LookPath("x100vi"); err == nil {
		names = appendNew(names, p)
	}
	if exe, err := os.Executable(); err == nil {
		names = appendNew(names, exe, resolved(exe))
	}
	return names
}

func starlarkList(items []string) string {
	quoted := make([]string, len(items))
	for i, it := range items {
		quoted[i] = `"` + strings.ReplaceAll(strings.ReplaceAll(it, `\`, `\\`), `"`, `\"`) + `"`
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

// CodexRules is a Codex .rules file: read-only commands run unsandboxed, writes run unsandboxed after
// a prompt. nil tools or launchers mean ToolPaths() and LauncherPaths("").
func CodexRules(tools, launchers []string) string {
	if tools == nil {
		tools = ToolPaths()
	}
	if launchers == nil {
		launchers = LauncherPaths("")
	}
	prefixes := []string{starlarkList(tools)}
	if len(launchers) > 0 {
		prefixes = append(prefixes, starlarkList([]string{"sh", "bash"})+", "+starlarkList(launchers))
	}
	blocks := []string{
		"# x100vi: let Codex reach the camera. Generated by `x100vi sandbox-help`.\n" +
			"# USB devices are invisible inside the sandbox, so these commands must run outside it.\n" +
			"# Reading and previewing run without a prompt; anything that writes still asks first.\n",
	}
	groups := []struct {
		commands []string
		decision string
		why      string
	}{{ReadCommands, "allow", whyRead}, {WriteCommands, "prompt", whyWrite}}
	for _, prefix := range prefixes {
		for _, g := range groups {
			blocks = append(blocks, fmt.Sprintf("prefix_rule(\n"+
				"    pattern = [%s, %s],\n"+
				"    decision = \"%s\",\n"+
				"    justification = \"%s\",\n"+
				")\n", prefix, starlarkList(g.commands), g.decision, g.why))
		}
	}
	return strings.Join(blocks, "\n")
}

// WriteCodexRules saves rules to CodexRulesPath(), creating its folder, and returns the path.
func WriteCodexRules(rules string) (string, error) {
	p := CodexRulesPath()
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(p, []byte(rules), 0o644); err != nil {
		return "", err
	}
	return p, nil
}

// ClaudeSettingsFile is where ClaudeSettings belongs, as shown to people.
const ClaudeSettingsFile = "~/.claude/settings.json"

// ClaudeSettings is the settings.json fragment that keeps these commands out of Claude Code's sandbox:
// {"sandbox": {"excludedCommands": [...]}}. nil tools or launchers mean ToolPaths() and LauncherPaths("").
func ClaudeSettings(tools, launchers []string) map[string]any {
	if tools == nil {
		tools = ToolPaths()
	}
	if launchers == nil {
		launchers = LauncherPaths("")
	}
	patterns := []string{}
	for _, t := range tools {
		patterns = append(patterns, t+" *")
	}
	for _, p := range launchers {
		patterns = append(patterns, "sh "+p+" *")
	}
	return map[string]any{"sandbox": map[string]any{"excludedCommands": patterns}}
}
